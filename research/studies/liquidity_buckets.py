"""Assign H3 liquidity buckets by the rule frozen in research/universe.md. Run BEFORE any IC.

Rule: on in-sample dates only, per symbol, median trades per minute and median spread in
ticks (book_valid rows). Rank by trades/min descending (ties: spread in ticks ascending).
Ranks 1-2 → high, 3-4 → mid, 5-6 → low. Writes configs/liquidity_buckets.yaml.

Uses only book files (market activity), never labels or returns.

    python -m research.studies.liquidity_buckets
"""

from __future__ import annotations

import numpy as np
import polars as pl
import yaml

from common.meta import git_sha, read_metadata, utc_now_iso
from common.paths import CONFIGS, book_path
from common.universe import load_universe

NAMES = ("high", "mid", "low")


def symbol_stats(symbol: str, dates: tuple[str, ...]) -> dict:
    per_min, spread_ticks, used = [], [], []
    for d in dates:
        p = book_path(symbol, d)
        if not p.exists():
            continue
        tick = float(read_metadata(str(p))["tick_size"])
        df = pl.read_parquet(p, columns=["ts_ns", "n_trades", "bid_px_1", "ask_px_1", "book_valid"])
        # trades per minute over the minutes where the book was valid throughout
        m = (
            df.with_columns((pl.col("ts_ns") // 60_000_000_000).alias("minute"))
            .group_by("minute")
            .agg(pl.col("n_trades").sum(), pl.col("book_valid").all())
            .filter(pl.col("book_valid"))
        )
        per_min.append(m["n_trades"].to_numpy())
        v = df.filter(pl.col("book_valid"))
        spread_ticks.append(((v["ask_px_1"] - v["bid_px_1"]) / tick).to_numpy())
        used.append(d)
    if not used:
        return {"median_trades_per_min": np.nan, "median_spread_ticks": np.nan, "dates_used": 0}
    return {
        "median_trades_per_min": float(np.median(np.concatenate(per_min))),
        "median_spread_ticks": float(np.median(np.concatenate(spread_ticks))),
        "dates_used": len(used),
    }


def main() -> None:
    u = load_universe()
    stats = {s: symbol_stats(s, u.in_sample) for s in u.symbols}
    missing = {
        s: len(u.in_sample) - v["dates_used"]
        for s, v in stats.items()
        if v["dates_used"] < len(u.in_sample)
    }
    if missing:
        raise SystemExit(f"book files missing for in-sample dates: {missing}")
    order = sorted(
        u.symbols,
        key=lambda s: (-stats[s]["median_trades_per_min"], stats[s]["median_spread_ticks"]),
    )
    buckets = {s: NAMES[i // 2] for i, s in enumerate(order)}
    doc = {
        "version": 1,
        "computed_at": utc_now_iso(),
        "code_git_sha": git_sha(),
        "rule": "research/universe.md#liquidity-buckets-h3",
        "universe_version": u.version,
        "buckets": {b: [s for s in order if buckets[s] == b] for b in NAMES},
        "stats": {
            s: {k: round(v, 4) if isinstance(v, float) else v for k, v in stats[s].items()}
            for s in order
        },
    }
    out = CONFIGS / "liquidity_buckets.yaml"
    out.write_text(
        "# Generated by research/studies/liquidity_buckets.py before any IC was computed.\n"
        + yaml.safe_dump(doc, sort_keys=False)
    )
    print(out.read_text())


if __name__ == "__main__":
    main()
